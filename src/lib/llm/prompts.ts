const READER_PERSONA = `# 想定読者
想定読者は、挙式日・会場が決まっており、衣装（ドレス・和装）もおおむね決まっている。これから決めるのは挙式・披露宴の中身である —— 進行とタイムライン、演出、席次と席札、余興、スピーチや余興の依頼、BGM、装花、料理、引出物、ペーパーアイテム、写真と映像、ゲストの過ごしやすさ、当日の段取り。この読者が求めているのは「何が人気か」ではなく「実際に式を挙げた人が、何を、なぜそう判断したか」である。`;

/**
 * 有用度判定 5 項目（すべて 0/1/2）の指示。定義は spec.md §9.2〜§9.4 と同一の内容。
 *
 * 点数（重み付け）は絶対に出力させない。点数は `src/lib/scoring/usefulness.ts`
 * の `computeUsefulnessScore()` がコード側で計算する設計であり、LLM に点数を
 * 出させた瞬間に「重み調整を再課金ゼロのコード変更で完結させる」という設計
 * 全体が無効になる。
 *
 * 意図的に書いていないこと: 「衣装・ドレスの記事を減点せよ」という指示。
 * 衣装のみの記事は `ceremonyDecision` ゲート（コード側の
 * `computeUsefulnessScore`）で構造的に沈む設計のため、ここに二重で書く必要は
 * なく、「衣装のみではない」のような二重否定のブール項目を LLM に判定させると
 * 最も不安定になる。
 */
const USEFULNESS_CRITERIA_RULES = `# 有用度判定（5項目をそれぞれ 0 / 1 / 2 の整数で判定。点数（合計）は絶対に出力しないこと）
上の想定読者にとって役に立つ投稿かどうかを、以下の各項目について判定する。

## スケールの使い方（最重要。ここを誤ると全記事が 2 になり掲載順が機能しなくなる）
- **0 = 該当しない**。
- **1 = 該当する（標準）**。条件を満たす記事の大半はここ。「当事者が書いている」「当日の話がある」「具体的な記述がある」程度なら 1。
- **2 = 例外的に突出している場合のみ**。他の同種記事と並べたとき、明らかに一段深い・詳しい・具体的だと言える場合に限る。感覚の目安として、判定する記事のうち 2 を付けてよいのは上位 2〜3 割程度。
- 迷ったら低い方（0 か 1）を選ぶ。「悪くないから 2」ではなく「飛び抜けているから 2」。

※ ceremonyDecision と weddingDayContent は別軸：ceremonyDecision は「その話題が式の中身の意思決定に役立つか（トピック適合）」、weddingDayContent は「フルパッケージ結婚式（挙式＋披露宴）の当日の実施内容を扱っているか（対象範囲）」。

- firsthand: 書き手が実際に挙式・披露宴を経験した立場から書いているか。新婦本人に限らず、新郎・両家家族、およびプランナー・司会者・カメラマン・装花担当など式に立ち会う職能者の実務経験も含む。2=当事者本人が自分の式について具体的なエピソードを交えて書いている、1=当事者だが記述が概説的、または近しい立場からの一般的な記述、0=第三者・まとめ・伝聞のみ。
- ceremonyDecision: 挙式・披露宴の中身の意思決定（進行・タイムライン・演出・席次・席札・余興・スピーチ・BGM・装花・料理・引出物・ペーパーアイテム・挙式当日の写真/映像・ゲストの過ごしやすさ・当日段取り）に効くか。2=複数の意思決定項目について「何を・なぜそう決めたか」という判断材料が読み取れる、1=意思決定に関わる話題に触れている、0=ほぼ無関係。
- specific: **当日の実施内容の具体性**。固有の選択・数値・実際にやったこと／やらなかった理由・現場でどう進んだか。2=複数の場面で具体的な選択・数値・理由が詳述されている、1=一部具体的な記述はあるが要点は抽象的、0=心構え・一般論・感想のみ。
- weddingDayContent: **フルパッケージ結婚式（挙式＋披露宴）の当日の実施内容**を扱っているか。進行の実際の流れ・演出・余興・料理・装花・衣装の着用感・BGMと当日の展開・ゲストの反応・当日のトラブルと対応など。2=当日の進行や複数の場面が時系列・具体的に描写されている、1=当日に触れるが断片的または準備寄り、**0=フォトウェディング・前撮り・後撮りなどの別撮影、式場探し・見積もり比較・日取り決定・規模や形式の合意形成といった準備段階のみ、あるいは挙式披露宴を伴わない内容**。語の有無ではなく当日の実施事実が描写されている実質で判定する。
- promotional: 事業者による集客・自社サービスへの誘導の度合い。判別基準は「読者が別の会場・別の業者で式を挙げる場合にも役立つか」。0=集客要素が実質的にない、1=自社サービスへの言及や導線はあるが主目的は情報提供で他式場でも役立つ、2=文章中で過剰かつ明確に自社サービス・特定式場への誘導を行っているもののみ（減点対象。実例紹介に安易に 2 を付けない）。

「卒花」「花嫁レポ」「#プレ花嫁」等の語がタイトル・本文に含まれること自体は加点材料ではない。逆にこれらの語が一切無くても、実際の挙式・披露宴の経験に基づく知見であれば同等に扱うこと。

判断材料が本文抜粋に無い場合、各項目は 0 とせよ。本文にあるだろうと推測して 1 や 2 にしてはならない。`;

const RATIONALE_RULES = `# topicAnchor のルール（必ず守ること）
- 目的: 読者が「まだ知らない何かが、そこに具体的にある」と分かるよう、記事の「視点・場面・争点」をアンカーで開示する。結論・結果・具体的数値は書かない（ゼロクリック化の回避）。
- クリック誘引: この記事ならではの独自性（他の記事には無い切り口・具体的な状況・意外な着眼点・当事者ならではの気づき）を一つ選び、それを読者が「続きを読みたい」と感じる形で提示する。ありふれた一般論ではなく、この1本を開く理由になる要素を出すこと。ただし煽り表現には頼らない（下記「禁止」参照）。文の形（問いかけ・体言止め・述語で結ぶ 等）は自由。
- 長さ: 18〜36字を目安に。10字台は短すぎる。上限40字。
- 語彙: 助詞・接続表現・述語・言い換えは自由。記事の内容に即していれば、本文抜粋にある語をそのまま使う必要はない（自然な日本語で言い換えてよい）。ただし記事が扱っていない話題を作り出さないこと。
- 禁止: 記事固有の具体数値（半角/全角/漢数字・金額・日付）、人物の氏名・ニックネーム・SNS アカウント名・個人と結びつく会場名・店舗名。煽り・価値付与（衝撃/必見/実は/知らないと損/最強/絶対/驚愕/やばい/話題/最高/究極/世界一 等）、二人称命令（〜しよう/〜すべき）、メタ表現（〜についての記事/〜を紹介 等）。
- 表題非重複: タイトルの単なる言い換えにしない。タイトルに無い視点・場面・争点を必ず一つ足すこと。`;

